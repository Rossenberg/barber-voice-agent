// ---------------------------------------------------------------- load

async function load() {
  state = await api("GET", "/api/admin/state");
  draft = structuredClone(state.services);
  servicesDirty = false;
  $("loginView").hidden = true;
  $("appView").hidden = false;
  $("logoutBtn").hidden = false;
  renderAll(true);
}

/** Refreshes bookings and the on/off state without touching unsaved edits. */
async function refresh() {
  if (!state || document.hidden) return;
  try {
    const fresh = await api("GET", "/api/admin/state");
    state.bookings = fresh.bookings;
    state.today = fresh.today;
    state.settings.enabled = fresh.settings.enabled;
    renderPower();
    renderBookings();
  } catch {}
}

function renderAll(withForms) {
  $("brandName").textContent = state.settings.shop_name;
  renderPower();
  renderBookings();
  renderServices();
  renderServiceOptions();
  if (withForms) renderSettings();
  else renderHours(readHours());
}

// ---------------------------------------------------------------- power switch

function renderPower() {
  const on = state.settings.enabled;
  $("powerCard").dataset.on = String(on);
  $("powerSwitch").setAttribute("aria-checked", String(on));
  $("powerTitle").textContent = t(on ? "power.on" : "power.off");
  $("powerSub").textContent = t(on ? "power.onSub" : "power.offSub");
}

$("powerSwitch").addEventListener("click", async () => {
  const next = !state.settings.enabled;
  state.settings.enabled = next;
  renderPower();
  try {
    await api("PUT", "/api/admin/settings", { enabled: next });
    toast(t(next ? "power.on" : "power.off"));
  } catch {
    state.settings.enabled = !next;
    renderPower();
    toast(t("error"), true);
  }
});

