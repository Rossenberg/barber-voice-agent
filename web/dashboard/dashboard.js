function input(type, value, attrs = {}) {
  return Object.assign(el("input", "input"), { type, value: value ?? "" }, attrs);
}

function field(labelKey, control) {
  const f = el("label", "field");
  f.append(el("span", "", t(labelKey)), control);
  return f;
}

