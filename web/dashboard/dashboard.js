// ---------------------------------------------------------------- bookings

function dayLabel(date) {
  if (date === state.today) return t("today");
  if (date === addDays(state.today, 1)) return t("tomorrow");
  const d = new Date(date + "T00:00:00Z");
  return `${t("days")[d.getUTCDay()]}, ${String(d.getUTCDate()).padStart(2, "0")}.${String(d.getUTCMonth() + 1).padStart(2, "0")}`;
}

function bookingCard(b) {
  const card = el("div", `bk${b.status === "cancelled" ? " cancelled" : ""}`);
  const time = el("div", "bk-time", hhmm(b.start_min));
  time.append(el("small", "", hhmm(b.end_min)));
  const main = el("div", "bk-main");
  main.append(el("b", "", b.service_name));
  const who = el("div", "who");
  who.append(el("span", "", b.client_name || t("booking.noName")));
  if (b.phone) who.append(Object.assign(el("a", "", b.phone), { href: `tel:${b.phone}` }));
  who.append(el("span", `badge${b.source === "assistant" ? " ai" : ""}`, t(b.source === "assistant" ? "booking.ai" : "booking.manual")));
  main.append(who);
  card.append(time, main);
  if (b.status === "confirmed" && b.date >= state.today) {
    const btn = el("button", "mini", t("booking.cancel"));
    btn.addEventListener("click", async () => {
      if (!confirm(t("booking.confirmCancel"))) return;
      try {
        await api("POST", `/api/admin/bookings/${b.id}/cancel`);
        b.status = "cancelled";
        renderBookings();
      } catch {
        toast(t("error"), true);
      }
    });
    card.append(btn);
  } else card.append(el("span"));
  return card;
}

function renderBookings() {
  const list = $("bookingList");
  const upcoming = state.bookings.filter((b) => b.date >= state.today);
  const past = state.bookings.filter((b) => b.date < state.today).reverse();
  list.replaceChildren();
  if (!upcoming.some((b) => b.status === "confirmed")) list.append(el("div", "empty", t("booking.empty")));
  const byDay = new Map();
  for (const b of upcoming) byDay.set(b.date, [...(byDay.get(b.date) ?? []), b]);
  for (const [date, items] of byDay) {
    const head = el("div", "day-head");
    head.append(el("b", "", dayLabel(date)), el("span", "", String(items.filter((b) => b.status === "confirmed").length)));
    list.append(head, ...items.map(bookingCard));
  }
  if (past.length) {
    const head = el("div", "day-head");
    head.append(el("b", "", t("booking.past")), el("span", "", String(past.length)));
    list.append(head, ...past.slice(0, 20).map(bookingCard));
  }
}

function renderServiceOptions() {
  const sel = $("bService");
  const current = sel.value;
  sel.replaceChildren(...state.services.filter((s) => s.active).map((s) => Object.assign(el("option", "", `${lang === "hy" ? s.name_hy : s.name_en} · ${s.duration_min}′`), { value: s.id })));
  if (current) sel.value = current;
}

