function renderHours(hours) {
  const order = [1, 2, 3, 4, 5, 6, 0]; // Monday first
  $("hoursList").replaceChildren(
    ...order.map((d) => {
      const h = hours[d];
      const row = el("div", `hour-row${h ? "" : " closed"}`);
      row.dataset.day = d;
      row.append(el("b", "", t("days")[d]));
      const open = el("label", "check");
      const box = Object.assign(el("input"), { type: "checkbox", checked: Boolean(h) });
      box.addEventListener("change", () => row.classList.toggle("closed", !box.checked));
      open.append(box, el("span", "", t("s.open")));
      row.append(open);
      const times = el("div", "times");
      times.append(input("time", hhmm(h ? h[0] : 600), { step: 900 }), el("span", "muted", "—"), input("time", hhmm(h ? h[1] : 1260), { step: 900 }));
      row.append(times);
      return row;
    }),
  );
}

function readHours() {
  const hours = Array(7).fill(null);
  document.querySelectorAll(".hour-row").forEach((row) => {
    const [from, to] = row.querySelectorAll('input[type="time"]');
    if (row.querySelector('input[type="checkbox"]').checked && from.value && to.value) hours[Number(row.dataset.day)] = [toMin(from.value), toMin(to.value)];
  });
  return document.querySelectorAll(".hour-row").length ? hours : state.settings.hours;
}

function renderSettings() {
  const s = state.settings;
  $("sShop").value = s.shop_name;
  $("sShopSpoken").value = s.shop_name_spoken ?? "";
  $("sAddress").value = s.address;
  $("sGreeting").value = s.greeting;
  $("sBarbers").value = s.barbers;
  $("sExtra").value = s.extra_instructions;
  renderHours(s.hours);
}

