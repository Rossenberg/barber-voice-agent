$("saveServicesBtn").addEventListener("click", async () => {
  const used = new Set();
  const payload = draft
    .filter((s) => s.name_hy.trim() || s.name_en.trim())
    .map((s) => {
      let id = s.id || slug(s);
      while (used.has(id)) id = `${id}_2`;
      used.add(id);
      return { ...s, id };
    });
  try {
    const { services } = await api("PUT", "/api/admin/services", { services: payload });
    state.services = services;
    draft = structuredClone(services);
    servicesDirty = false;
    renderServices();
    renderServiceOptions();
    toast(t("saved"));
  } catch (err) {
    toast(`${t("error")}: ${err.message}`, true);
  }
});

