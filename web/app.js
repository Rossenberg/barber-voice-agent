let sceneRun = 0, sceneIdx = 0;
async function playScene() {
  const run = ++sceneRun;
  const scenes = t("scenes"), sc = scenes[sceneIdx % scenes.length];
  const body = $("sceneBody"), chip = $("sceneChip"), slot = $("sceneSlot"), cal = document.querySelector(".mini-cal");
  const wait = (ms) => new Promise((r) => setTimeout(r, reduceMotion ? 0 : ms));
  const alive = () => run === sceneRun;
  body.replaceChildren();
  body.classList.remove("leaving");
  chip.classList.remove("show");
  slot.classList.remove("filled");
  $("sceneInd").textContent = sc.ind;
  $("sceneInd").classList.remove("swap"); void $("sceneInd").offsetWidth; $("sceneInd").classList.add("swap");
  $("sceneDots").innerHTML = scenes.map((_, i) => `<i${i === sceneIdx % scenes.length ? ' class="on"' : ""}></i>`).join("");
  $("sceneChipText").textContent = sc.chip[1];
  chip.querySelector("b").textContent = sc.chip[0];
  $("sceneIco").innerHTML = sc.order ? BAG_ICO : CHECK_ICO;
  cal.classList.toggle("off", !sc.cal);
  if (sc.cal) {
    $("sceneDay").textContent = sc.cal[0];
    cal.querySelectorAll("[data-time]").forEach((el, i) => (el.textContent = sc.cal[i + 1]));
  }
  for (const [who, text, extra] of sc.msgs) {
    if (who === "a" && !reduceMotion) {
      const dots = document.createElement("div");
      dots.className = "sb a typing";
      dots.textContent = "•••";
      body.append(dots);
      body.scrollTo({ top: body.scrollHeight, behavior: "smooth" });
      await wait(900);
      if (!alive()) return;
      dots.remove();
    }
    const b = document.createElement("div");
    if (who === "p") {
      // a client shares the shop's Instagram post and asks about it
      b.className = "sb c post";
      b.innerHTML = `<span class="sp-card"><span class="sp-img" style="--h:${sc.hue ?? 150}"></span><span class="sp-cap"><small>Instagram</small><b></b></span></span><span class="sp-q"></span>`;
      b.querySelector("b").textContent = text;
      b.querySelector(".sp-q").textContent = extra;
    } else {
      b.className = `sb ${who}`;
      b.textContent = text;
    }
    body.append(b);
    body.scrollTo({ top: body.scrollHeight, behavior: "smooth" });
    await wait(who === "a" ? 1500 : 1700);
    if (!alive()) return;
  }
  slot.classList.add("filled");
  chip.classList.add("show");
  if (reduceMotion) return;
  await wait(3800);
  if (!alive()) return;
  body.classList.add("leaving");
  chip.classList.remove("show");
  await wait(600);
  if (!alive()) return;
  sceneIdx++;
  playScene();
}

// Loss calculator: unanswered messages a day × share that would book × average check × 30 days.
const fmtAmd = (n) => `${Math.round(n).toLocaleString("ru-RU").replace(/\u00a0/g, " ")} ֏`;
function calc() {
  const missed = +$("rMissed").value, check = +$("rCheck").value, rate = +$("rRate").value;
  $("vMissed").textContent = missed;
  $("vCheck").textContent = fmtAmd(check);
  $("vRate").textContent = `${rate}%`;
  $("calcOut").textContent = fmtAmd(missed * (rate / 100) * check * 30);
  for (const r of document.querySelectorAll("#calc input[type=range]")) r.style.setProperty("--p", `${((r.value - r.min) / (r.max - r.min)) * 100}%`);
}
document.querySelectorAll("#calc input[type=range]").forEach((r) => r.addEventListener("input", calc));

