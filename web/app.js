const chatLog = $("chatLog");
let chatId = null, chatHistory = [], chatBusy = false;

function chatAdd(text, cls) {
  const div = document.createElement("div");
  div.className = `msg ${cls}`;
  div.textContent = text;
  chatLog.append(div);
  chatLog.scrollTop = chatLog.scrollHeight;
  return div;
}

async function openChat() {
  // the greeting follows the page language (Armenian: the owner's own greeting); restarted on a language switch until they write
  if (chatHistory.some((m) => m.role === "user")) return;
  chatHistory = [];
  chatLog.replaceChildren();
  if (config && !config.enabled) return chatAdd(t("chat.off"), "tool");
  const greeting = (lang === "ru" ? t("chat.greet") : config?.greeting ?? "Բարև Ձեզ։ Ինչո՞վ օգնեմ։").replaceAll("{shop}", config?.shop_name ?? "").replaceAll("{name}", "Անի");
  chatHistory.push({ role: "assistant", content: greeting });
  chatAdd(greeting, "agent");
}

async function sendChat(text) {
  text = text.trim();
  if (!text || chatBusy) return;
  chatBusy = true;
  $("chatChips").hidden = true;
  chatHistory.push({ role: "user", content: text });
  chatAdd(text, "user");
  const typing = chatAdd("•••", "agent typing");
  try {
    const res = await fetch("/api/chat", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ id: chatId, messages: chatHistory }) });
    const data = await res.json();
    if (!res.ok || data.reply === undefined) throw new Error(data.error || res.status);
    chatId = data.id;
    typing.remove();
    if (data.booked) chatAdd(t("chat.booked"), "tool ok");
    if (data.reply) { chatHistory.push({ role: "assistant", content: data.reply }); chatAdd(data.reply, "agent"); } // empty: nothing to say
  } catch (err) {
    console.error(err);
    typing.remove();
    chatHistory.pop();
    chatAdd(t("chat.error"), "tool");
  } finally {
    chatBusy = false;
    $("chatInput").focus();
  }
}

